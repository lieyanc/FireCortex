package dockermgr

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	managedports "github.com/lieyanc/FireCortex/backend/internal/ports/managedinfra"
)

const (
	// ComposeFileName 是托管数据根目录下自动同步落盘的 Docker Compose 文件名。
	ComposeFileName = "docker-compose.yml"
	// ComposeEnvFileName 是供 docker-compose.yml 引用的 0600 凭据环境变量文件名。
	ComposeEnvFileName = ".env"
)

// SyncComposeFiles 将当前托管基础设施声明原子落盘到 <rootDir>/docker-compose.yml（0640）
// 与 <rootDir>/.env（0600），便于运维审计、服务器迁移或在脱离主程序时通过 docker compose 恢复。
func SyncComposeFiles(rootDir string, state ComposeState) (composePath string, envPath string, err error) {
	resolvedRoot, err := ValidateHostDir(rootDir)
	if err != nil {
		return "", "", err
	}

	composePath = filepath.Join(resolvedRoot, ComposeFileName)
	envPath = filepath.Join(resolvedRoot, ComposeEnvFileName)

	envBytes := renderComposeEnv(state)
	composeBytes := renderComposeYAML(state)

	if err := writeFileAtomic(envPath, envBytes, 0o600); err != nil {
		return "", "", fmt.Errorf("write %s: %w", envPath, err)
	}
	if err := writeFileAtomic(composePath, composeBytes, 0o640); err != nil {
		return "", "", fmt.Errorf("write %s: %w", composePath, err)
	}
	return composePath, envPath, nil
}

// ReadComposeFile 读取落盘的 docker-compose.yml（文件仅含变量引用，不含明文密码）。
func ReadComposeFile(rootDir string) (string, error) {
	resolvedRoot, err := ValidateHostDir(rootDir)
	if err != nil {
		return "", err
	}
	data, err := os.ReadFile(filepath.Join(resolvedRoot, ComposeFileName))
	if err != nil {
		return "", err
	}
	return string(data), nil
}

func renderComposeEnv(state ComposeState) []byte {
	var buf bytes.Buffer
	buf.WriteString("# Auto-generated by FireCortex managed infrastructure. Mode 0600.\n")
	buf.WriteString("# Do not commit this file to version control.\n")
	if netName := strings.TrimSpace(state.Network); netName != "" {
		fmt.Fprintf(&buf, "FIRECORTEX_DOCKER_NETWORK=%s\n", envEscape(netName))
	} else {
		buf.WriteString("FIRECORTEX_DOCKER_NETWORK=firecortex-network\n")
	}
	if state.Postgres != nil {
		pg := state.Postgres
		pgImage := nonEmptyOr(pg.Image, managedports.DefaultPostgresImage)
		fmt.Fprintf(&buf, "FIRECORTEX_POSTGRES_IMAGE=%s\n", envEscape(RewriteImageWithMirror(pgImage, state.RegistryMirror)))
		fmt.Fprintf(&buf, "FIRECORTEX_POSTGRES_PORT=%d\n", portOrDefault(pg.Port, 5432))
		fmt.Fprintf(&buf, "FIRECORTEX_POSTGRES_USER=%s\n", envEscape(nonEmptyOr(pg.User, "firecortex")))
		fmt.Fprintf(&buf, "FIRECORTEX_POSTGRES_PASSWORD=%s\n", envEscape(pg.Password))
		fmt.Fprintf(&buf, "FIRECORTEX_POSTGRES_DB=%s\n", envEscape(nonEmptyOr(pg.Database, "firecortex")))
		fmt.Fprintf(&buf, "FIRECORTEX_POSTGRES_DATA_DIR=%s\n", envEscape(pg.DataDir))
	}
	if state.Redis != nil {
		rd := state.Redis
		fmt.Fprintf(&buf, "FIRECORTEX_REDIS_IMAGE=%s\n", envEscape(RewriteImageWithMirror(rd.Image, state.RegistryMirror)))
		fmt.Fprintf(&buf, "FIRECORTEX_REDIS_PORT=%d\n", portOrDefault(rd.Port, 6379))
		fmt.Fprintf(&buf, "FIRECORTEX_REDIS_PASSWORD=%s\n", envEscape(rd.Password))
		fmt.Fprintf(&buf, "FIRECORTEX_REDIS_DATA_DIR=%s\n", envEscape(rd.DataDir))
	}
	for _, sc := range state.Sidecars {
		prefix := "FIRECORTEX_" + strings.ToUpper(sc.ServiceID)
		fmt.Fprintf(&buf, "%s_IMAGE=%s\n", prefix, envEscape(RewriteImageWithMirror(sc.Image, sc.RegistryMirror)))
		fmt.Fprintf(&buf, "%s_PORT=%d\n", prefix, sc.HostPort)
	}
	return buf.Bytes()
}

func renderComposeYAML(state ComposeState) []byte {
	var buf bytes.Buffer
	buf.WriteString("# Auto-generated and kept in sync by FireCortex.\n")
	buf.WriteString("# Disaster recovery: docker compose --env-file .env -f docker-compose.yml up -d\n\n")
	buf.WriteString("services:\n")

	if state.Postgres != nil {
		pgImage := nonEmptyOr(state.Postgres.Image, managedports.DefaultPostgresImage)
		pgLayout := managedports.ResolvePostgresContainerLayout(pgImage)
		buf.WriteString("  postgres:\n")
		fmt.Fprintf(&buf, "    container_name: %s\n", PostgresContainerName)
		buf.WriteString("    image: ${FIRECORTEX_POSTGRES_IMAGE}\n")
		buf.WriteString("    restart: unless-stopped\n")
		buf.WriteString("    labels:\n")
		fmt.Fprintf(&buf, "      %s: \"true\"\n", ManagedLabelKey)
		fmt.Fprintf(&buf, "      %s: %q\n", ServiceLabelKey, CoreServicePostgres)
		buf.WriteString("    environment:\n")
		buf.WriteString("      POSTGRES_USER: ${FIRECORTEX_POSTGRES_USER}\n")
		buf.WriteString("      POSTGRES_PASSWORD: ${FIRECORTEX_POSTGRES_PASSWORD}\n")
		buf.WriteString("      POSTGRES_DB: ${FIRECORTEX_POSTGRES_DB}\n")
		if pgLayout.PGData != "" {
			fmt.Fprintf(&buf, "      PGDATA: %s\n", pgLayout.PGData)
		}
		if pgLayout.InitDBArgs != "" {
			fmt.Fprintf(&buf, "      POSTGRES_INITDB_ARGS: %q\n", pgLayout.InitDBArgs)
		}
		buf.WriteString("    ports:\n")
		buf.WriteString("      - \"127.0.0.1:${FIRECORTEX_POSTGRES_PORT}:5432\"\n")
		buf.WriteString("    volumes:\n")
		fmt.Fprintf(&buf, "      - \"${FIRECORTEX_POSTGRES_DATA_DIR}:%s\"\n", pgLayout.MountTarget)
		if state.Postgres.MemoryLimitMB > 0 {
			fmt.Fprintf(&buf, "    mem_limit: %dm\n", state.Postgres.MemoryLimitMB)
		}
		buf.WriteString("    healthcheck:\n")
		buf.WriteString("      test: [\"CMD-SHELL\", \"pg_isready -U $$POSTGRES_USER -d $$POSTGRES_DB\"]\n")
		buf.WriteString("      interval: 5s\n")
		buf.WriteString("      timeout: 5s\n")
		buf.WriteString("      retries: 10\n")
		buf.WriteString("    networks:\n")
		buf.WriteString("      - firecortex\n")
	}

	if state.Redis != nil {
		buf.WriteString("\n  redis:\n")
		fmt.Fprintf(&buf, "    container_name: %s\n", RedisContainerName)
		buf.WriteString("    image: ${FIRECORTEX_REDIS_IMAGE}\n")
		buf.WriteString("    restart: unless-stopped\n")
		buf.WriteString("    labels:\n")
		fmt.Fprintf(&buf, "      %s: \"true\"\n", ManagedLabelKey)
		fmt.Fprintf(&buf, "      %s: %q\n", ServiceLabelKey, CoreServiceRedis)
		buf.WriteString("    command:\n")
		buf.WriteString("      - redis-server\n")
		buf.WriteString("      - --appendonly\n")
		buf.WriteString("      - \"yes\"\n")
		buf.WriteString("      - --appendfsync\n")
		buf.WriteString("      - everysec\n")
		buf.WriteString("      - --save\n")
		buf.WriteString("      - \"900\"\n")
		buf.WriteString("      - \"1\"\n")
		buf.WriteString("      - --save\n")
		buf.WriteString("      - \"300\"\n")
		buf.WriteString("      - \"10\"\n")
		buf.WriteString("      - --dir\n")
		buf.WriteString("      - /data\n")
		if state.Redis.Password != "" {
			buf.WriteString("      - --requirepass\n")
			buf.WriteString("      - ${FIRECORTEX_REDIS_PASSWORD}\n")
			buf.WriteString("    environment:\n")
			buf.WriteString("      REDISCLI_AUTH: ${FIRECORTEX_REDIS_PASSWORD}\n")
		}
		buf.WriteString("    ports:\n")
		buf.WriteString("      - \"127.0.0.1:${FIRECORTEX_REDIS_PORT}:6379\"\n")
		buf.WriteString("    volumes:\n")
		buf.WriteString("      - \"${FIRECORTEX_REDIS_DATA_DIR}:/data\"\n")
		if state.Redis.MemoryLimitMB > 0 {
			fmt.Fprintf(&buf, "    mem_limit: %dm\n", state.Redis.MemoryLimitMB)
		}
		buf.WriteString("    healthcheck:\n")
		buf.WriteString("      test: [\"CMD-SHELL\", \"redis-cli ping | grep -q PONG\"]\n")
		buf.WriteString("      interval: 5s\n")
		buf.WriteString("      timeout: 5s\n")
		buf.WriteString("      retries: 10\n")
		buf.WriteString("    networks:\n")
		buf.WriteString("      - firecortex\n")
	}

	for _, sc := range state.Sidecars {
		prefix := "FIRECORTEX_" + strings.ToUpper(sc.ServiceID)
		fmt.Fprintf(&buf, "\n  %s:\n", sc.ServiceID)
		fmt.Fprintf(&buf, "    container_name: %s\n", sc.ContainerName)
		fmt.Fprintf(&buf, "    image: ${%s_IMAGE}\n", prefix)
		buf.WriteString("    restart: unless-stopped\n")
		buf.WriteString("    labels:\n")
		fmt.Fprintf(&buf, "      %s: \"true\"\n", ManagedLabelKey)
		fmt.Fprintf(&buf, "      %s: %q\n", ServiceLabelKey, sc.ServiceID)
		if len(sc.Env) > 0 {
			buf.WriteString("    environment:\n")
			for _, envLine := range sc.Env {
				fmt.Fprintf(&buf, "      - %q\n", envLine)
			}
		}
		buf.WriteString("    ports:\n")
		fmt.Fprintf(&buf, "      - \"127.0.0.1:${%s_PORT}:%d\"\n", prefix, sc.ContainerPort)
		if strings.TrimSpace(sc.DataDir) != "" && strings.TrimSpace(sc.ContainerDataDir) != "" {
			buf.WriteString("    volumes:\n")
			fmt.Fprintf(&buf, "      - %q\n", strings.TrimSpace(sc.DataDir)+":"+strings.TrimSpace(sc.ContainerDataDir))
		}
		if sc.MemoryLimitMB > 0 {
			fmt.Fprintf(&buf, "    mem_limit: %dm\n", sc.MemoryLimitMB)
		}
		buf.WriteString("    networks:\n")
		buf.WriteString("      - firecortex\n")
	}

	buf.WriteString("\nnetworks:\n")
	buf.WriteString("  firecortex:\n")
	buf.WriteString("    name: ${FIRECORTEX_DOCKER_NETWORK}\n")
	buf.WriteString("    driver: bridge\n")
	return buf.Bytes()
}

func envEscape(value string) string {
	// 单值内无空白和特殊字符时直接输出，否则用单引号安全包裹。
	if value == "" {
		return ""
	}
	if !strings.ContainsAny(value, " \t\n\r\"'#$\\") {
		return value
	}
	return "'" + strings.ReplaceAll(value, "'", `'\''`) + "'"
}

func portOrDefault(port, fallback int) int {
	if port > 0 {
		return port
	}
	return fallback
}

func nonEmptyOr(value, fallback string) string {
	if trimmed := strings.TrimSpace(value); trimmed != "" {
		return trimmed
	}
	return fallback
}
